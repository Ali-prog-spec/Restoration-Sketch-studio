"""Write outputs/RESULTS_SUMMARY.txt: every headline number, read from the saved
evaluation artifacts (nothing is typed by hand).

    python scripts/make_results_summary.py
"""

import _bootstrap  # noqa: F401

import json

import pandas as pd

from src.utils.config import resolve


def j(p):
    return json.loads(resolve(p).read_text(encoding="utf-8"))


def csv(p, **kw):
    return pd.read_csv(resolve(p), **kw)


def main():
    L = []
    w = L.append
    w("=" * 78)
    w(" RESULTS SUMMARY - Generative AI Assignment 1 (FINAL runs, official test sets)")
    w(" Generated by scripts/make_results_summary.py from the files in outputs/")
    w("=" * 78)

    # ---------------- datasets ----------------
    s = j("data/manifests/oxford_split.json")["counts"]
    f = j("data/manifests/fs2k_split.json")["counts"]
    w("\nDATASETS")
    w(f"  Oxford-IIIT Pet : train {s['train']} / val {s['val']} / test {s['test']} images (seed 42)")
    w("  Test manifest   : 36,690 corrupted test records (clean + 3 corruptions x 3 levels)")
    w(f"  FS2K            : train {f['train']} / val {f['val']} / test {f['test']} pairs (15% val, stratified by style)")

    # ---------------- task 1 ----------------
    t = csv("outputs/task1/metrics_by_type.csv", index_col=0)
    sk = csv("outputs/task1/metrics_by_type_skip0.csv", index_col=0)
    w("\nTASK 1 - UNIVERSAL DENOISING AUTOENCODER   (SSIM: higher is better, 1.0 = perfect)")
    w(f"  {'condition':<14}{'input SSIM':>11}{'output SSIM':>13}{'output PSNR':>13}{'output L1':>11}")
    for c in ["clean", "salt_pepper", "blur", "occlusion", "overall"]:
        r = t.loc[c]
        w(f"  {c:<14}{r['input_ssim']:>11.3f}{r['ssim']:>13.3f}{r['psnr']:>11.2f}dB{r['l1']:>11.4f}")
    w(f"  Limited-skip ablation (not deployed): overall SSIM {sk.loc['overall','ssim']:.3f}")

    # ---------------- task 2 ----------------
    d = j("outputs/task2/test_summary.json")
    c = d["classifier"]
    pc = csv("outputs/task2/classifier_per_class.csv", index_col=0)
    w("\nTASK 2 - CORRUPTION CLASSIFIER")
    w(f"  Accuracy        : {c['accuracy'] * 100:.2f} %")
    w(f"  Macro precision : {c['macro_precision']:.4f}")
    w(f"  Macro recall    : {c['macro_recall']:.4f}")
    w(f"  Macro F1        : {c['macro_f1']:.4f}")
    for cls, r in pc.iterrows():
        w(f"    {cls:<12} precision {r['precision']:.4f}  recall {r['recall']:.4f}  F1 {r['f1']:.4f}  (n={int(r['support'])})")
    w("TASK 2 - HARD ROUTING (restoration)")
    w(f"  Oracle routing    SSIM {d['oracle_overall']['ssim']:.4f}")
    w(f"  Predicted routing SSIM {d['predicted_overall']['ssim']:.4f}")
    w(f"  Misrouted records: {d['n_misrouted']} of 36,690; classifier-caused failures: {d['n_classifier_caused_failures']}")

    # ---------------- task 3 ----------------
    t3 = csv("outputs/task3/metrics_by_type.csv", index_col=0)
    mw = csv("outputs/task3/routing_mean_weights_by_type.csv", index_col=0)
    dg = j("outputs/task3/routing_diagnostics.json")
    w("\nTASK 3 - SOFT MIXTURE OF EXPERTS")
    for cname in ["clean", "salt_pepper", "blur", "occlusion", "overall"]:
        w(f"  {cname:<14} SSIM {t3.loc[cname, 'ssim']:.3f}   PSNR {t3.loc[cname, 'psnr']:.2f} dB")
    w("  Mean routing weight per true condition (Identity / Salt / Blur / Occlusion):")
    for cname, r in mw.iterrows():
        w(f"    {cname:<12} " + "  ".join(f"{v:.3f}" for v in r.values))
    w(f"  Inactive experts: {dg['inactive_experts(max mean weight < 0.05)'] or 'none'}")

    # ---------------- comparison ----------------
    w("\nRESTORATION SYSTEMS COMPARED (overall test SSIM)")
    w(f"  corrupted input     {t.loc['overall', 'input_ssim']:.3f}")
    w(f"  Task 1 universal    {t.loc['overall', 'ssim']:.3f}")
    w(f"  Task 2 hard routing {d['predicted_overall']['ssim']:.3f}")
    w(f"  Task 3 soft MoE     {t3.loc['overall', 'ssim']:.3f}")

    # ---------------- task 4 ----------------
    t4 = csv("outputs/task4/test_metrics_by_style.csv")
    s4 = j("outputs/task4/test_summary.json")
    w("\nTASK 4 - FACE-TO-SKETCH cGAN (official FS2K test set; L1: lower is better)")
    for _, r in t4.iterrows():
        name = f"Style {r['style']}" if r["style"] != "overall" else "overall"
        w(f"  {name:<9} L1 {r['l1']:.4f}   SSIM {r['ssim']:.3f}   PSNR {r['psnr']:.2f} dB   (n={int(r['n'])})")
    si = s4["style_influence"]
    w(f"  Style influence (mean |G(x,a)-G(x,b)|): 1v2 {si['1v2']:.3f}, 1v3 {si['1v3']:.3f}, 2v3 {si['2v3']:.3f}")
    w(f"  Deployed checkpoint: epoch {s4['epoch']}")

    # ---------------- optuna ----------------
    w("\nOPTUNA STUDIES (baseline = PDF values = trial 0; objective lower is better)")
    for k, path in [("Task 1", "task1"), ("Task 2 classifier", "task2/classifier"),
                    ("Task 2 specialists", "task2/specialists"), ("Task 3", "task3"), ("Task 4", "task4")]:
        st = j(f"outputs/{path}/optuna/final/study_summary.json")
        tr = csv(f"outputs/{path}/optuna/final/trials.csv")
        w(f"  {k:<19} trials {st['n_trials_total']:>2}  baseline {tr.loc[0, 'value']:.4f}  ->  best {st['best_value']:.4f} (trial {st['best_trial_number']})")

    # ---------------- onnx ----------------
    rep = j("outputs/onnx/validation_report.json")
    w("\nONNX EXPORT CHECK (PyTorch vs ONNX Runtime)")
    for k, r in rep.items():
        if k == "summary":
            continue
        diffs = ", ".join(f"{o['max_abs_diff']:.1e}" for o in r["outputs"])
        w(f"  {k:<18} max |diff| {diffs:<20} {'PASS' if r['passed'] else 'FAIL'}")
    w(f"  All passed: {rep['summary']['all_passed']}")

    out = resolve("outputs/RESULTS_SUMMARY.txt")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"\n-> {out}")


if __name__ == "__main__":
    main()
